// Репозиторий, из которого приложение проверяет обновления.
val updateRepo = providers.gradleProperty("ordercontrol.updateRepo")
    .getOrElse("MaxKarpyza/OrderControl")

// Подпись release-сборки: переменные окружения (CI) или keystore.properties
// локально. Файл keystore.properties и сам ключ в репозиторий не попадают.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(env: String, property: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() }
        ?: keystoreProperties.getProperty(property)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("KEYSTORE_FILE", "storeFile")?.let { rootProject.file(it) }

android {
    namespace = "ru.ordercontrol"
    compileSdk = 37

    defaultConfig {
        applicationId = "ru.ordercontrol"
        minSdk = 30
        targetSdk = 35
        // Схема версий — doc/versions.md: 0.0.100 и +1 к последнему числу
        // на каждую отдельную доработку.
        versionCode = 128
        versionName = "0.0.128"

        buildConfigField("String", "UPDATE_REPO", "\"$updateRepo\"")
    }

    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = releaseStoreFile
                storePassword = signingValue("KEYSTORE_PASSWORD", "storePassword")
                keyAlias = signingValue("KEY_ALIAS", "keyAlias")
                keyPassword = signingValue("KEY_PASSWORD", "keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (releaseStoreFile != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

